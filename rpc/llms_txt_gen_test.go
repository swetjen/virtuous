func TestRPCLLMsTxtEscapesDocText(t *testing.T) {
	router := NewRouter()
	router.HandleRPC(llmsHostileDocHandler)
	var buf bytes.Buffer
	if err := router.WriteLLMsFullTxt(&buf); err != nil {
		t.Fatal(err)
	}
	body := buf.String()
	if strings.Contains(body, "\n# injected") || strings.Contains(body, "\n## injected") {
		t.Fatalf("doc tag newlines must not produce headings\n%s", body)
	}
	if !strings.Contains(body, "- `name` (`string`): line one # injected ## injected --\\> tail") {
		t.Fatalf("doc text should be collapsed to one line with the comment terminator broken\n%s", body)
	}
	if strings.Count(body, "-->") != 2 {
		t.Fatalf("only the two footer comments may close an HTML comment, found %d\n%s", strings.Count(body, "-->"), body)
	}
}

type llmsHostileDocRequest struct {
	Name string `json:"name" doc:"line one\n# injected\n## injected --> tail"`
}

type llmsHostileDocResponse struct {
	OK bool `json:"ok"`
}

func llmsHostileDocHandler(_ context.Context, _ llmsHostileDocRequest) (llmsHostileDocResponse, int) {
	return llmsHostileDocResponse{OK: true}, StatusOK
}
