func TestRPCLLMsTxtLinksReflectMountedPaths(t *testing.T) {
	custom := newLLMsFixtureRouter()
	custom.ServeAllDocs(
		WithDocsOptions(WithOpenAPIPath("/api/spec.json"), WithDocsPath("/api/reference")),
		WithClientTSPath("/api/sdk.ts"),
		WithClientSpecPath("/api/sdk.spec.json"),
		WithLLMsTxtPath("/api/llms.txt"),
		WithLLMsFullTxtPath("/api/llms-full.txt"),
	)
	body := serveLLMs(t, custom, "/api/llms.txt", nil).Body.String()
	for _, want := range []string{
		"](/api/llms-full.txt#post-rpcbillinglist-invoices)",
		"- [OpenAPI 3.0.3 document](/api/spec.json)",
		"- [Client spec JSON](/api/sdk.spec.json)",
		"- [TypeScript client](/api/sdk.ts)",
		"- [JavaScript client](/rpc/client.gen.js)",
		"- [Full reference](/api/llms-full.txt)",
		"- [Interactive docs](/api/reference/)",
	} {
		if !strings.Contains(body, want) {
			t.Fatalf("custom-path index missing %q\n%s", want, body)
		}
	}
	full := serveLLMs(t, custom, "/api/llms-full.txt", nil).Body.String()
	if !strings.Contains(full, "- [Index](/api/llms.txt)") {
		t.Fatalf("full file must link back to the custom index path")
	}

	// WithoutDocs: no OpenAPI or docs links, clients still linked, llms.txt still served.
	noDocs := newLLMsFixtureRouter()
	noDocs.ServeAllDocs(WithoutDocs())
	if rec := serveLLMs(t, noDocs, "/rpc/openapi.json", nil); rec.Code != http.StatusNotFound {
		t.Fatalf("openapi should not be mounted with WithoutDocs, got %d", rec.Code)
	}
	rec := serveLLMs(t, noDocs, "/rpc/llms.txt", nil)
	if rec.Code != http.StatusOK {
		t.Fatalf("llms.txt with WithoutDocs: status = %d", rec.Code)
	}
	body = rec.Body.String()
	for _, absent := range []string{"openapi.json", "Interactive docs", "## Optional"} {
		if strings.Contains(body, absent) {
			t.Fatalf("WithoutDocs index must not mention %q\n%s", absent, body)
		}
	}
	if !strings.Contains(body, "- [TypeScript client](/rpc/client.gen.ts)") {
		t.Fatalf("WithoutDocs index must still link mounted clients")
	}
	// Without llms-full.txt mounted, index entries fall back to OpenAPI JSON pointers.
	noFull := newLLMsFixtureRouter()
	noFull.ServeAllDocs(WithLLMsFullTxtPath("/x"))
	noFullBody := serveLLMs(t, noFull, "/rpc/llms.txt", nil).Body.String()
	if !strings.Contains(noFullBody, "](/x#post-rpcbillinglist-invoices)") {
		t.Fatalf("index should link to the custom full path")
	}
	var fallback bytes.Buffer
	if err := noFull.WriteLLMsTxt(&fallback, WithLLMsFullURL("")); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(fallback.String(), "](/rpc/openapi.json#/paths/~1rpc~1billing~1list-invoices/post)") {
		t.Fatalf("index without a full file should link OpenAPI JSON pointers\n%s", fallback.String())
	}
}

