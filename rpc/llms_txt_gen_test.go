// llmsGeneratedLinePattern masks the provenance footer line, which carries the
// release version and generation time.
var llmsGeneratedLinePattern = regexp.MustCompile(`<!-- Code generated by Virtuous [^\n]* -->`)

func normalizeLLMsGolden(data []byte) []byte {
	return llmsGeneratedLinePattern.ReplaceAll(data, []byte("<!-- Code generated by Virtuous vGOLDEN -->"))
}

// assertLLMsGolden byte-compares rendered output (with the provenance line
// masked) against the golden file. Regenerate after an intentional change with
//
//	UPDATE_LLMS_GOLDEN=1 go test ./rpc -run LLMsTxtGolden -count=1
//
// and review the golden diff before committing.
func assertLLMsGolden(t *testing.T, goldenPath string, got []byte) {
	t.Helper()
	normalized := normalizeLLMsGolden(got)
	if os.Getenv("UPDATE_LLMS_GOLDEN") == "1" {
		if err := os.WriteFile(goldenPath, normalized, 0644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		return
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("read golden (regenerate with UPDATE_LLMS_GOLDEN=1): %v", err)
	}
	if !bytes.Equal(normalized, want) {
		t.Fatalf("llms output differs from %s (regenerate with UPDATE_LLMS_GOLDEN=1 and review the diff)\ngot:\n%s", goldenPath, normalized)
	}
}

func TestRPCLLMsTxtGolden(t *testing.T) {
	router := newLLMsFixtureRouter()
	var index, full bytes.Buffer
	if err := router.WriteLLMsTxt(&index); err != nil {
		t.Fatalf("WriteLLMsTxt: %v", err)
	}
	if err := router.WriteLLMsFullTxt(&full); err != nil {
		t.Fatalf("WriteLLMsFullTxt: %v", err)
	}
	assertLLMsGolden(t, filepath.Join("testdata", "llms_txt_golden.md"), index.Bytes())
	assertLLMsGolden(t, filepath.Join("testdata", "llms_full_txt_golden.md"), full.Bytes())
}

func serveLLMs(t *testing.T, h http.Handler, path string, headers map[string]string) *httptest.ResponseRecorder {
	t.Helper()
	req := httptest.NewRequest(http.MethodGet, path, nil)
	for k, v := range headers {
		req.Header.Set(k, v)
	}
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	return rec
}

func assertLLMsShape(t *testing.T, body string) {
	t.Helper()
	lines := strings.Split(body, "\n")
	if len(lines) < 3 || !strings.HasPrefix(lines[0], "# ") {
		t.Fatalf("first line must be the H1, got %q", lines[0])
	}
	if lines[1] != "" || !strings.HasPrefix(lines[2], "> ") {
		t.Fatalf("H1 must be followed by a blank line and a blockquote, got %q / %q", lines[1], lines[2])
	}
	if !strings.Contains(body, "<!-- Virtuous llms.txt hash: ") || !strings.Contains(body, " UTC; DO NOT EDIT. -->") {
		t.Fatalf("missing provenance footer")
	}
}

func TestRPCServeAllDocsServesLLMsTxt(t *testing.T) {
	router := newLLMsFixtureRouter()
	router.ServeAllDocs()

	for _, path := range []string{"/rpc/llms.txt", "/rpc/llms-full.txt"} {
		rec := serveLLMs(t, router, path, nil)
		if rec.Code != http.StatusOK {
			t.Fatalf("%s status = %d", path, rec.Code)
		}
		if got := rec.Header().Get("Content-Type"); got != "text/markdown; charset=utf-8" {
			t.Fatalf("%s Content-Type = %q", path, got)
		}
		assertLLMsShape(t, rec.Body.String())
		etag := rec.Header().Get("ETag")
		if etag == "" {
			t.Fatalf("%s missing ETag", path)
		}
		rec2 := serveLLMs(t, router, path, map[string]string{"If-None-Match": etag})
		if rec2.Code != http.StatusNotModified {
			t.Fatalf("%s If-None-Match status = %d, want 304", path, rec2.Code)
		}
	}

	// The served index is the WriteLLMsTxt output with the default link set.
	var want bytes.Buffer
	if err := router.WriteLLMsTxt(&want); err != nil {
		t.Fatalf("WriteLLMsTxt: %v", err)
	}
	got := serveLLMs(t, router, "/rpc/llms.txt", nil).Body.Bytes()
	if !bytes.Equal(stripRPCGeneratedTimestamp(got), stripRPCGeneratedTimestamp(want.Bytes())) {
		t.Fatalf("served llms.txt differs from WriteLLMsTxt output")
	}
}

func TestRPCLLMsTxtIndexListsEveryRouteOnce(t *testing.T) {
	router := newLLMsFixtureRouter()
	var buf bytes.Buffer
	if err := router.WriteLLMsTxt(&buf); err != nil {
		t.Fatalf("WriteLLMsTxt: %v", err)
	}
	body := buf.String()
	for _, route := range router.Routes() {
		entry := "- [POST " + route.Path + "](/rpc/llms-full.txt#"
		if n := strings.Count(body, entry); n != 1 {
			t.Fatalf("route %s listed %d times, want 1", route.Path, n)
		}
	}
	checks := []string{
		"- [POST /rpc/billing/list-invoices](/rpc/llms-full.txt#post-rpcbillinglist-invoices): `InvoiceQuery` → `Page_Invoice` (auth: TokenAuth, SessionAuth)",
		"- [POST /rpc/billing/list-invoices-legacy](/rpc/llms-full.txt#post-rpcbillinglist-invoices-legacy): no request body → `Page_Invoice` (deprecated: Use billing.ListInvoices.)",
		"- [POST /rpc/media/get-asset](/rpc/llms-full.txt#post-rpcmediaget-asset): no request body → `Asset` (auth: KeyAuth)",
		"- **TokenAuth**: send header `Authorization: Bearer <token>`. Required by 1 endpoint: `POST /rpc/billing/list-invoices`.",
		"- **SessionAuth**: send cookie `session=<token>`.",
		"- **KeyAuth**: send query parameter `api_key=<token>`.",
	}
	for _, want := range checks {
		if !strings.Contains(body, want) {
			t.Fatalf("index missing %q\n%s", want, body)
		}
	}
	if strings.Contains(body, "list-invoices-legacy](/rpc/llms-full.txt#post-rpcbillinglist-invoices-legacy): no request body → `Page_Invoice` (auth") {
		t.Fatalf("unguarded route must not carry an auth marker")
	}
}

